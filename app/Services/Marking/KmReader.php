<?php

namespace App\Services\Marking;

/**
 * Единая читалка кода маркировки: из того, что прилетело со сканера или из
 * буфера обмена, достаёт КИ — первые 38 символов (01 + GTIN + 21 + серийник),
 * по которым код лежит в MARKCODES.
 *
 * Сканер отдаёт КМ в трёх видах, и все три должны читаться одинаково:
 *   (01)04600...(21)abc(91)EE12(92)...  — со скобками, режим кладовщика;
 *   0104600...21abc<GS>91EE12<GS>92...  — с разделителем групп GS1 (символ 29);
 *   0104600...21abc91EE1292...          — плоско, как копируют руками.
 *
 * Криптохвост (91/92) в КИ не входит. Режем по длине, а не по хвосту: серийник
 * состоит из чего угодно, включая цифры 9 и 1 (в базе таких кодов 8), скобки
 * (1526 кодов) и знаки < >. Поэтому и скобки снимаются только на своих местах —
 * там, где они могут быть только признаком применения, а не частью серийника.
 */
class KmReader
{
    /** Длина КИ: 01 + GTIN(14) + 21 + серийник(20). Проверено на всей базе кодов. */
    public const KI_LENGTH = 38;

    /** Разделитель групп GS1: сканер шлёт его символом 29. */
    private const GS = "\x1d";

    /** Длина «01» + GTIN: на этом месте в скобочном формате стоит (21). */
    private const GTIN_END = 16;

    /**
     * КИ из произвольного скана. Пусто — прочитать не удалось (не тот формат,
     * обрезанная строка, сканер в другой раскладке).
     */
    public static function ki(string $scan): string
    {
        $km = self::normalize($scan);

        // Код всегда начинается с AI 01; иначе это не КМ, а мусор из поля ввода.
        if (mb_strpos($km, '01') !== 0 || mb_strlen($km) < self::KI_LENGTH) {
            return '';
        }
        return mb_substr($km, 0, self::KI_LENGTH);
    }

    /**
     * Скан без служебного обрамления: сняты разделители групп, пробелы,
     * переводы строк и скобки двух первых применений. Скобки дальше по строке
     * не трогаем — они уже в криптохвосте, за пределами КИ.
     */
    public static function normalize(string $scan): string
    {
        // Пробелов и переносов в самом коде нет (проверено по базе), а из буфера
        // обмена и от сканера они приходят регулярно.
        $km = preg_replace('/\s+/u', '', str_replace(self::GS, '', $scan));

        if (mb_strpos($km, '(01)') !== 0) {
            return $km;
        }
        $km = '01' . mb_substr($km, 4);
        if (mb_substr($km, self::GTIN_END, 4) === '(21)') {
            $km = mb_substr($km, 0, self::GTIN_END) . '21' . mb_substr($km, self::GTIN_END + 4);
        }
        return $km;
    }
}
